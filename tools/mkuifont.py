#!/usr/bin/env python3
"""Generates the antialiased proportional fonts of the SynthOS desktop as C source.

Glyphs are 4-bit alpha bitmaps rendered from Inter (SIL Open Font License); characters Inter
lacks are taken from DejaVu (Bitstream Vera license).
The alpha data is LZ4-compressed; the kernel unpacks a font into the heap the first time it is drawn.
usage: tools/mkuifont.py > kernel/gui/uifont.c (needs Pillow)
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lz4pack  # noqa: E402

INTER = "/usr/share/fonts/opentype/inter/"
DEJAVU = "/usr/share/fonts/truetype/dejavu/"

SYMBOLS = ("−√⌫∞π•–—…←↑→↓↔✓✔✕✖×÷±≤≥≠°€№™©®▲▼◀▶■□●○★☆♪⌂☰⚙⌘⌥⇧⌃⏎⎋⇥›‹«»“”‘’·")
TEXT = sorted(set(list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + list(range(0x400, 0x460)) +
                  [ord(c) for c in SYMBOLS]))
BOX = list(range(0x2500, 0x2580)) + list(range(0x2580, 0x25A0))
GREEK = [ord(c) for c in "ΓΘΣΦΩαβδεπστφµ∙∩≡≈ⁿ²⌠⌡"]

FONTS = [
    ("font_sans", INTER + "Inter-Regular.otf", DEJAVU + "DejaVuSans.ttf", 13, TEXT),
    ("font_bold", INTER + "Inter-SemiBold.otf", DEJAVU + "DejaVuSans-Bold.ttf", 13, TEXT),
    ("font_small", INTER + "Inter-Medium.otf", DEJAVU + "DejaVuSans.ttf", 11, TEXT),
    ("font_title", INTER + "Inter-Bold.otf", DEJAVU + "DejaVuSans-Bold.ttf", 20, TEXT),
    ("font_large", INTER + "InterDisplay-SemiBold.otf", DEJAVU + "DejaVuSans-Bold.ttf", 26, TEXT),
    ("font_mono", DEJAVU + "DejaVuSansMono.ttf", DEJAVU + "DejaVuSansMono.ttf", 13, TEXT + GREEK),
    ("font_clock", INTER + "InterDisplay-SemiBold.otf", DEJAVU + "DejaVuSans-Bold.ttf", 92,
     [ord(c) for c in "0123456789: "]),
    ("font_clock_light", INTER + "InterDisplay-ExtraLight.otf", DEJAVU + "DejaVuSans.ttf", 92,
     [ord(c) for c in "0123456789: "]),
    ("font_clock_heavy", INTER + "InterDisplay-Black.otf", DEJAVU + "DejaVuSans-Bold.ttf", 92,
     [ord(c) for c in "0123456789: "]),
    ("font_clock_mono", DEJAVU + "DejaVuSansMono-Bold.ttf", DEJAVU + "DejaVuSansMono-Bold.ttf", 92,
     [ord(c) for c in "0123456789: "]),
    ("font_clock_serif", DEJAVU + "DejaVuSerif-Bold.ttf", DEJAVU + "DejaVuSerif-Bold.ttf", 92,
     [ord(c) for c in "0123456789: "]),
    ("font_display", INTER + "InterDisplay-Light.otf", DEJAVU + "DejaVuSans.ttf", 46,
     [ord(c) for c in " 0123456789.,-+e×÷−=%()ErorCandivbyzIlpt"]),
]


def missing(font, ch, ref):
    mask = font.getmask(ch, mode="L")
    return mask.size == ref.size and bytes(mask) == bytes(ref)


def render(path, fallback, size, codes):
    font = ImageFont.truetype(path, size)
    fb = ImageFont.truetype(fallback, size)
    ref = font.getmask("", mode="L")
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for code in sorted(set(codes)):
        ch = chr(code)
        use = font
        if code > 0x7F and missing(font, ch, ref):
            use = fb
        left, top, right, bottom = use.getbbox(ch)
        advance = int(round(use.getlength(ch)))
        w, h = max(0, right - left), max(0, bottom - top)
        if code != 0x20 and w == 0 and code > 0x7F:
            continue
        img = Image.new("L", (max(w, 1), max(h, 1)), 0)
        if w and h:
            ImageDraw.Draw(img).text((-left, -top), ch, font=use, fill=255)
        px = img.load()
        offset = len(data)
        for y in range(h):
            row = [min(15, (px[x, y] + 8) // 17) for x in range(w)]
            if len(row) % 2:
                row.append(0)
            for i in range(0, len(row), 2):
                data.append(row[i] << 4 | row[i + 1])
        glyphs.append((code, advance, w, h, left, top, offset))
    return ascent, descent, glyphs, data


def main():
    print("/* Generated by tools/mkuifont.py from Inter (SIL OFL) and DejaVu (Bitstream Vera license). Do not edit. */")
    print("#include <synth/gui.h>\n")
    for name, path, fallback, size, codes in FONTS:
        ascent, descent, glyphs, data = render(path, fallback, size, codes)
        packed = lz4pack.compress(data)
        print(f"static const uint8_t {name}_lz[] = {{")
        for i in range(0, len(packed), 24):
            print("    " + ", ".join(f"0x{b:02x}" for b in packed[i:i + 24]) + ",")
        print("};\n")
        print(f"static const uint8_t *{name}_alpha;\n")
        print(f"static const struct ui_glyph {name}_glyphs[] = {{")
        for g in glyphs:
            print("    {0x%04x, %d, %d, %d, %d, %d, %d}," % g)
        print("};\n")
        print(f"const struct ui_font {name} = {{{ascent + descent}, {ascent}, {len(glyphs)}, {name}_glyphs, {name}_lz, "
              f"{len(packed)}, {len(data)}, &{name}_alpha}};\n")


main()

#!/usr/bin/env python3
"""Generates the antialiased proportional fonts of the SynthOS desktop as C source.

Glyphs are 4-bit alpha bitmaps rendered from DejaVu Sans (Bitstream Vera license).
usage: tools/mkuifont.py > kernel/gui/uifont.c (needs Pillow)
"""
from PIL import Image, ImageDraw, ImageFont

FONTS = [
    ("font_sans", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 12),
    ("font_bold", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 12),
    ("font_title", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 18),
    ("font_mono", "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 12),
]

SYMBOLS = "−√⌫∞π•–—…←↑→↓↔✓✔✕✖×÷±≤≥≠°€№™©®▲▼◀▶■□●○★☆♪⌂☰⚙"
CODES = sorted(set(list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + list(range(0x400, 0x460)) +
                   [ord(c) for c in SYMBOLS]))


def render(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for code in CODES:
        ch = chr(code)
        try:
            mask = font.getmask(ch, mode="L")
        except Exception:
            continue
        left, top, right, bottom = font.getbbox(ch)
        advance = int(round(font.getlength(ch)))
        w, h = max(0, right - left), max(0, bottom - top)
        img = Image.new("L", (max(w, 1), max(h, 1)), 0)
        if w and h:
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255)
        px = img.load()
        offset = len(data)
        for y in range(h):
            row = [min(15, (px[x, y] + 8) // 17) for x in range(w)]
            if len(row) % 2:
                row.append(0)
            for i in range(0, len(row), 2):
                data.append(row[i] << 4 | row[i + 1])
        if code != 0x20 and w == 0 and code > 0x7F:
            continue
        glyphs.append((code, advance, w, h, left, top, offset))
    return ascent, descent, glyphs, data


def main():
    print("/* Generated by tools/mkuifont.py from DejaVu Sans (Bitstream Vera license). Do not edit. */")
    print("#include <synth/gui.h>\n")
    for name, path, size in FONTS:
        ascent, descent, glyphs, data = render(path, size)
        print(f"static const uint8_t {name}_alpha[] = {{")
        for i in range(0, len(data), 24):
            print("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        print("};\n")
        print(f"static const struct ui_glyph {name}_glyphs[] = {{")
        for g in glyphs:
            print("    {0x%04x, %d, %d, %d, %d, %d, %d}," % g)
        print("};\n")
        print(f"const struct ui_font {name} = {{{ascent + descent}, {ascent}, {len(glyphs)}, {name}_glyphs, {name}_alpha}};\n")


main()
